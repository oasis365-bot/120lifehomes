function regionCd(name) { const r = REGIONS.find(x => x.name === name); return r ? r.cd : ""; }
function regionName(cd) { const r = REGIONS.find(x => x.cd === String(cd)); return r ? r.name : cd; }
function ymd(d) {
  if (!d) return "";
  const s = String(d);
  return s.length >= 10 ? s.slice(0, 10).replace(/-/g, ".") : s;
}
